// Спрашивает у пользователя, сколько ему лет.
// Если пользователь введет отрицательное число — возвращает 
// 'Вы ввели неправильное значение'.

// Если пользователь введет число от  0 до  12//  — возвращает 'Привет, друг!'.
// Если пользователь введет число больше или равно 13  — возвращает  'Добро пожаловать!' .
// Для проверки вывода можете вызвать функцию в  alert. Например,
// alert(correctAge(prompt("Сколько вам лет?")))

// Подсказка: можете выполнить это задание с помощью оператора if else.
function userYears(){
const userInput = prompt("Сколько вам лет?"); 

// В данном случае просто вернем пустую строку для завершения работы функции.
    if (userInput === null) {
        return "";
    }

    //  Преобразуем введенную строку в целое число.
   
    const age = parseInt(userInput, 10);

     
    // Сначала проверим, что это вообще число.
       if (isNaN(age)) {
        return 'Вы ввели неправильное значение';
    }

    // Затем проверяем отрицательное число.
    if (age < 0) {
        return 'Вы ввели неправильное значение';
    }
    // Проверяем диапазон от 0 до 12 включительно.
    else if (age >= 0 && age <= 12) {
        return 'Привет, друг!';
    }
    // Все остальные валидные числа будут больше или равны 13.
    else {
        return 'Добро пожаловать!';
    }
}