// Напишите функцию, которая выполняет следующий алгоритм:

// Запрашивает у пользователя число.
// Проверяет, является ли введенное значение числом.
// Если значение не является числом, возвращает строку 
// 'Переданный параметр не является числом'.
// Если значение является числом, возвращает строку 
// 'n в кубе равняется <получившееся значение>', где n — введенное число,
//  а <получившееся значение> — число, возведенное в куб.
// Проверьте работу функции с числами от 0 до 10.

function get_number() {
  // Исправлена опечатка: unction -> function
  const userInput = prompt("Введите число: ");

  // Если пользователь нажал "Отмена", prompt вернет null.
  if (userInput === null) {
      return;
  }

  // Проверяем, является ли ввод числом.
  // Для надежности сначала пытаемся преобразовать строку в число.
  const number = parseFloat(userInput);
  
  // Number.isNaN() проверяет значение уже после преобразования
  if (Number.isNaN(number)) {
      // Исправлено: input -> number (или userInput, но number логичнее)
      return 'Переданный параметр не является числом';
  } else {
      // Вычисляем куб
      const cube = number ** 3;
      // Возвращаем строку в нужном формате
      return `n в кубе равняется ${cube}`;
  }
}

// Проверяем работу функции. Вызов get_number() без аргументов.
// Исправлено: get_number(i) -> get_number()
for (let i = 0; i <= 10; i++) {
  // Результат функции будет выводиться в консоль 11 раз,
  // каждый раз запрашивая ввод у пользователя.
  console.log(`Итерация ${i}:`, get_number());
}